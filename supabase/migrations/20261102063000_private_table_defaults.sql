-- New tables created by application migrations must opt in to public access.
-- Existing table grants, authenticated clients and backend access remain unchanged.
begin;
set local lock_timeout='5s';
set local statement_timeout='30s';
alter default privileges for role postgres in schema public revoke all on tables from public,anon;
alter default privileges for role postgres in schema public revoke all on sequences from public,anon;
-- Exercise the defaults in a savepoint so no probe table remains after commit.
savepoint default_access_probe;
create table public.__private_default_probe_20261102(id bigint generated by default as identity primary key);
do $verify_defaults$
declare p text;
begin
 if has_table_privilege('anon','public.__private_default_probe_20261102','SELECT')
 or has_table_privilege('anon','public.__private_default_probe_20261102','INSERT')
 or has_table_privilege('anon','public.__private_default_probe_20261102','UPDATE')
 or has_table_privilege('anon','public.__private_default_probe_20261102','DELETE') then
  raise exception 'New table still exposed to anonymous access';
 end if;
 foreach p in array array['SELECT','INSERT','UPDATE','DELETE'] loop
  if not has_table_privilege('authenticated','public.__private_default_probe_20261102',p)
  or not has_table_privilege('service_role','public.__private_default_probe_20261102',p) then
   raise exception 'Expected existing signed-in/backend defaults missing: %',p;
  end if;
 end loop;
end $verify_defaults$;
rollback to savepoint default_access_probe;
release savepoint default_access_probe;
commit;
